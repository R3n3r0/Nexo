// SetBucketEvents implements AdminClient.
func (c *client) SetBucketEvents(ctx context.Context, bucket string, cfg BucketNotifications) (*BucketNotifications, error) {
	subs := make([]EventSubscription, 0, len(cfg.Subscriptions))
	for _, sub := range cfg.Subscriptions {
		sub.Events = nonNilStrings(sub.Events)
		subs = append(subs, sub)
	}
	cfg.Subscriptions = subs
	var out BucketNotifications
	return &out, c.do(ctx, request{method: http.MethodPut, path: pathOf("buckets", bucket, "events"), body: cfg}, &out)
}

