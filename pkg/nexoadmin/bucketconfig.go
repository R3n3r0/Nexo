// --- CORS --------------------------------------------------------------------

// GetBucketCORS implements AdminClient.
func (c *client) GetBucketCORS(ctx context.Context, bucket string) (*CORSConfiguration, error) {
	var out CORSConfiguration
	return &out, c.do(ctx, request{method: http.MethodGet, path: pathOf("buckets", bucket, "cors")}, &out)
}

// SetBucketCORS implements AdminClient.
func (c *client) SetBucketCORS(ctx context.Context, bucket string, cfg CORSConfiguration) (*CORSConfiguration, error) {
	rules := make([]CORSRule, 0, len(cfg.Rules))
	for _, r := range cfg.Rules {
		// The required lists travel as arrays, never null.
		r.AllowedOrigins, r.AllowedMethods = nonNilStrings(r.AllowedOrigins), nonNilStrings(r.AllowedMethods)
		rules = append(rules, r)
	}
	cfg.Rules = rules
	var out CORSConfiguration
	return &out, c.do(ctx, request{method: http.MethodPut, path: pathOf("buckets", bucket, "cors"), body: cfg}, &out)
}

// DeleteBucketCORS implements AdminClient.
func (c *client) DeleteBucketCORS(ctx context.Context, bucket string) error {
	return c.do(ctx, request{method: http.MethodDelete, path: pathOf("buckets", bucket, "cors")}, nil)
}

// --- Object Lock and attributes ------------------------------------------------

// versionQuery names an object version.
func versionQuery(key, versionID string) url.Values {
	q := url.Values{"key": {key}}
	if versionID != "" {
		q.Set("versionId", versionID)
	}
	return q
}

// GetObjectRetention implements AdminClient.
func (c *client) GetObjectRetention(ctx context.Context, bucket, key, versionID string) (*ObjectRetention, error) {
	var out ObjectRetention
	return &out, c.do(ctx, request{method: http.MethodGet, path: pathOf("buckets", bucket, "objects", "retention"), query: versionQuery(key, versionID)}, &out)
}

// SetObjectRetention implements AdminClient.
func (c *client) SetObjectRetention(ctx context.Context, bucket, key, versionID string, in SetObjectRetentionRequest) (*ObjectRetention, error) {
	var out ObjectRetention
	return &out, c.do(ctx, request{method: http.MethodPut, path: pathOf("buckets", bucket, "objects", "retention"), query: versionQuery(key, versionID), body: in}, &out)
}

// GetObjectLegalHold implements AdminClient.
func (c *client) GetObjectLegalHold(ctx context.Context, bucket, key, versionID string) (*ObjectLegalHold, error) {
	var out ObjectLegalHold
	return &out, c.do(ctx, request{method: http.MethodGet, path: pathOf("buckets", bucket, "objects", "legal-hold"), query: versionQuery(key, versionID)}, &out)
}

// SetObjectLegalHold implements AdminClient.
func (c *client) SetObjectLegalHold(ctx context.Context, bucket, key, versionID, status string) (*ObjectLegalHold, error) {
	var out ObjectLegalHold
	return &out, c.do(ctx, request{method: http.MethodPut, path: pathOf("buckets", bucket, "objects", "legal-hold"), query: versionQuery(key, versionID),
		body: ObjectLegalHold{Status: status}}, &out)
}

// GetObjectAttributes implements AdminClient.
func (c *client) GetObjectAttributes(ctx context.Context, bucket, key string, opts ObjectAttributesOptions) (*ObjectAttributes, error) {
	q := versionQuery(key, opts.VersionID)
	if opts.MaxParts > 0 {
		q.Set("maxParts", strconv.Itoa(opts.MaxParts))
	}
	if opts.PartNumberMarker > 0 {
		q.Set("partNumberMarker", strconv.Itoa(opts.PartNumberMarker))
	}
	var out ObjectAttributes
	return &out, c.do(ctx, request{method: http.MethodGet, path: pathOf("buckets", bucket, "objects", "attributes"), query: q}, &out)
}
