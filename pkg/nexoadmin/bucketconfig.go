// --- types -------------------------------------------------------------------

// RuleError locates an invalid rule of a bucket configuration
// (APIError.RuleErrors).
type RuleError struct {
	// Rule is the 1-based index of the rule, 0 for the whole
	// configuration.
	Rule int    `json:"rule"`
	ID   string `json:"id,omitempty"`
	// Code is the S3 error code (InvalidArgument, MalformedXML...).
	Code    string `json:"code"`
	Message string `json:"message"`
}

// LifecycleConfiguration is the lifecycle configuration of a bucket.
type LifecycleConfiguration struct {
	Rules []LifecycleRule `json:"rules"`
}

// LifecycleRule is one lifecycle rule. A number set to 0 is sent and
// validated as such (the server rejects a zero Days): leave the pointer
// nil for an absent one.
type LifecycleRule struct {
	// ID is generated by the server when empty.
	ID string `json:"id,omitempty"`
	// Enabled is the status of the rule; nil means enabled.
	Enabled               *bool                           `json:"enabled,omitempty"`
	Filter                *LifecycleFilter                `json:"filter,omitempty"`
	Expiration            *LifecycleExpiration            `json:"expiration,omitempty"`
	NoncurrentExpiration  *LifecycleNoncurrentExpiration  `json:"noncurrentExpiration,omitempty"`
	AbortIncompleteUpload *LifecycleAbortUpload           `json:"abortIncompleteUpload,omitempty"`
	Transitions           []LifecycleTransition           `json:"transitions,omitempty"`
	NoncurrentTransitions []LifecycleNoncurrentTransition `json:"noncurrentTransitions,omitempty"`
}

// LifecycleFilter selects the objects of a rule.
type LifecycleFilter struct {
	Prefix          string            `json:"prefix,omitempty"`
	Tags            map[string]string `json:"tags,omitempty"`
	SizeGreaterThan *int64            `json:"sizeGreaterThan,omitempty"`
	SizeLessThan    *int64            `json:"sizeLessThan,omitempty"`
}

// LifecycleExpiration expires the current versions: exactly one of Days,
// Date (an ISO 8601 date at midnight UTC) and ExpiredObjectDeleteMarker.
type LifecycleExpiration struct {
	Days                      *int   `json:"days,omitempty"`
	Date                      string `json:"date,omitempty"`
	ExpiredObjectDeleteMarker bool   `json:"expiredObjectDeleteMarker,omitempty"`
}

// LifecycleNoncurrentExpiration removes the noncurrent versions.
type LifecycleNoncurrentExpiration struct {
	NoncurrentDays          *int `json:"noncurrentDays,omitempty"`
	NewerNoncurrentVersions *int `json:"newerNoncurrentVersions,omitempty"`
}

// LifecycleAbortUpload aborts the incomplete multipart uploads.
type LifecycleAbortUpload struct {
	DaysAfterInitiation *int `json:"daysAfterInitiation,omitempty"`
}

// LifecycleTransition moves the current versions to a remote tier.
type LifecycleTransition struct {
	Days         *int   `json:"days,omitempty"`
	Date         string `json:"date,omitempty"`
	StorageClass string `json:"storageClass"`
}

// LifecycleNoncurrentTransition moves the noncurrent versions to a
// remote tier.
type LifecycleNoncurrentTransition struct {
	NoncurrentDays          *int   `json:"noncurrentDays,omitempty"`
	NewerNoncurrentVersions *int   `json:"newerNoncurrentVersions,omitempty"`
	StorageClass            string `json:"storageClass"`
}

// LifecycleApplyResult reports an immediate application of the lifecycle.
type LifecycleApplyResult struct {
	Buckets        int `json:"buckets"`
	Versions       int `json:"versions"`
	Deleted        int `json:"deleted"`
	DeleteMarkers  int `json:"deleteMarkers"`
	UploadsAborted int `json:"uploadsAborted"`
	Locked         int `json:"locked"`
}

// BucketNotifications are the event subscriptions of a bucket.
type BucketNotifications struct {
	Subscriptions []EventSubscription `json:"subscriptions"`
}

// EventSubscription routes the events of a bucket to a target.
type EventSubscription struct {
	ID string `json:"id,omitempty"`
	// ARN names the target (NotifyTarget.ARN).
	ARN    string   `json:"arn"`
	Events []string `json:"events"`
	Prefix string   `json:"prefix,omitempty"`
	Suffix string   `json:"suffix,omitempty"`
}

// NotifyTarget is a notification target with its delivery state.
type NotifyTarget struct {
	ID            string `json:"id"`
	Type          string `json:"type"`
	ARN           string `json:"arn"`
	Enabled       bool   `json:"enabled"`
	Endpoint      string `json:"endpoint,omitempty"`
	Online        bool   `json:"online"`
	PendingEvents int    `json:"pendingEvents"`
	LastError     string `json:"lastError,omitempty"`
}

// NotifyTargetTest is the outcome of a test event.
type NotifyTargetTest struct {
	Target    string `json:"target"`
	Delivered bool   `json:"delivered"`
	Error     string `json:"error,omitempty"`
}

// CORSConfiguration is the CORS configuration of a bucket.
type CORSConfiguration struct {
	Rules []CORSRule `json:"rules"`
}

// CORSRule is one CORS rule.
type CORSRule struct {
	ID             string   `json:"id,omitempty"`
	AllowedOrigins []string `json:"allowedOrigins"`
	AllowedMethods []string `json:"allowedMethods"`
	AllowedHeaders []string `json:"allowedHeaders,omitempty"`
	ExposeHeaders  []string `json:"exposeHeaders,omitempty"`
	MaxAgeSeconds  *int     `json:"maxAgeSeconds,omitempty"`
}

// MediaConfiguration is the video configuration of a bucket: the first
// rule selecting a key applies.
type MediaConfiguration struct {
	Rules []MediaRule `json:"rules"`
}

// MediaRule selects videos or images by key prefix and suffix and names
// what the media worker derives from them.
type MediaRule struct {
	ID         string           `json:"id"`
	Prefix     string           `json:"prefix,omitempty"`
	Suffixes   []string         `json:"suffixes,omitempty"`
	Renditions []string         `json:"renditions,omitempty"`
	Poster     bool             `json:"poster,omitempty"`
	Thumbnails *MediaThumbnails `json:"thumbnails,omitempty"`
	// Images makes an image rule (default suffixes: the image formats the
	// worker decodes): the variants of every image it selects. An image
	// rule has no renditions, poster or thumbnails.
	Images *MediaImages `json:"images,omitempty"`
	// Subtitles asks for automatic subtitles of the videos: the speech
	// transcribed, then translated.
	Subtitles *MediaSubtitles `json:"subtitles,omitempty"`
}

// MediaSubtitles configures the automatic subtitles of a rule.
type MediaSubtitles struct {
	// Source is the spoken language (BCP 47); empty detects it.
	Source string `json:"source,omitempty"`
	// Languages are the translations to produce.
	Languages []string `json:"languages,omitempty"`
}

// MediaImages configures the variants of an image rule.
type MediaImages struct {
	// Formats of the variants: avif, webp, jpeg, png (default all).
	Formats []string `json:"formats,omitempty"`
	// Widths of the variants in pixels, 16 to 8192 (default 160, 320,
	// 640, 1280, 1920, 2560); those not smaller than the image are
	// skipped, and each format also gets the image at its own size.
	Widths []int `json:"widths,omitempty"`
}

// MediaThumbnails configures the timeline thumbnails of a rule.
type MediaThumbnails struct {
	// Interval is a Go duration from 1s to 10m (default 10s).
	Interval string `json:"interval,omitempty"`
}

// MediaStatus is the processing state of a video or an image by the
// media worker.
type MediaStatus struct {
	// State is processing, done or failed; none when the worker never
	// processed the version.
	State string `json:"state"`
	// Current reports outputs derived from the current content of the
	// version (only they are served); stale outputs are not.
	Current   bool   `json:"current"`
	VersionID string `json:"versionId,omitempty"`
	Error     string `json:"error,omitempty"`
	// Step is the step in progress or the one that failed.
	Step string `json:"step,omitempty"`
	// Rule is the id of the rule that selected the video.
	Rule string `json:"rule,omitempty"`
	// Duration of the video in seconds.
	Duration   float64                `json:"duration,omitempty"`
	Width      int                    `json:"width,omitempty"`
	Height     int                    `json:"height,omitempty"`
	Renditions []MediaRenditionOutput `json:"renditions,omitempty"`
	Poster     bool                   `json:"poster,omitempty"`
	Thumbnails *MediaThumbnailsOutput `json:"thumbnails,omitempty"`
	// Images are the variants of an image (Width and Height are then the
	// size of the image).
	Images []MediaImageOutput `json:"images,omitempty"`
	// Alpha reports an image with transparency.
	Alpha bool `json:"alpha,omitempty"`
	// Subtitles are the languages of the automatic subtitle tracks the
	// worker made; Language is the spoken language it detected.
	Subtitles []string `json:"subtitles,omitempty"`
	Language  string   `json:"language,omitempty"`
	// SubtitlesError is why the automatic subtitles failed (the other
	// outputs are served nonetheless).
	SubtitlesError string     `json:"subtitlesError,omitempty"`
	Updated        *time.Time `json:"updated,omitempty"`
}

// MediaImageOutput is a variant of an image produced by the media worker.
type MediaImageOutput struct {
	Format string `json:"format"`
	// Width is the width the rule asked for, 0 for the image at its own
	// size; PixelWidth and PixelHeight are the size of the variant.
	Width       int    `json:"width"`
	PixelWidth  int    `json:"pixelWidth"`
	PixelHeight int    `json:"pixelHeight"`
	Size        int64  `json:"size"`
	ContentType string `json:"contentType"`
	// URL serves the variant: a path of the server
	// (/api/v1/buckets/{bucket}/objects/image?key=...).
	URL string `json:"url"`
}

// MediaRenditionOutput is a rendition produced by the media worker.
type MediaRenditionOutput struct {
	Name      string `json:"name"`
	Width     int    `json:"width"`
	Height    int    `json:"height"`
	Bandwidth int    `json:"bandwidth"`
}

// MediaThumbnailsOutput is the thumbnail sprite produced by the media
// worker: Count tiles of Width x Height in a grid of Columns, one every
// Interval seconds.
type MediaThumbnailsOutput struct {
	Interval float64 `json:"interval"`
	Width    int     `json:"width"`
	Height   int     `json:"height"`
	Columns  int     `json:"columns"`
	Count    int     `json:"count"`
}

// ObjectRetention is the Object Lock retention of a version (no Mode when
// it has none).
type ObjectRetention struct {
	VersionID   string     `json:"versionId,omitempty"`
	Mode        string     `json:"mode,omitempty"`
	RetainUntil *time.Time `json:"retainUntil,omitempty"`
}

// SetObjectRetentionRequest sets a retention (Mode and RetainUntil) or
// removes it (neither).
type SetObjectRetentionRequest struct {
	Mode        string     `json:"mode,omitempty"`
	RetainUntil *time.Time `json:"retainUntil,omitempty"`
	// BypassGovernance shortens or removes a GOVERNANCE retention.
	BypassGovernance bool `json:"bypassGovernance,omitempty"`
}

// ObjectLegalHold is the legal hold of a version: ON or OFF.
type ObjectLegalHold struct {
	VersionID string `json:"versionId,omitempty"`
	Status    string `json:"status"`
}

// Checksum is the additional checksum of an object or a part.
type Checksum struct {
	Algorithm string `json:"algorithm"`
	Type      string `json:"type,omitempty"`
	Value     string `json:"value"`
}

// ObjectPart is a part of a multipart object.
type ObjectPart struct {
	PartNumber int       `json:"partNumber"`
	Size       int64     `json:"size"`
	Checksum   *Checksum `json:"checksum,omitempty"`
}

// ObjectAttributes describes a version without its content.
type ObjectAttributes struct {
	Key                  string       `json:"key"`
	VersionID            string       `json:"versionId,omitempty"`
	ETag                 string       `json:"etag"`
	Size                 int64        `json:"size"`
	LastModified         time.Time    `json:"lastModified"`
	StorageClass         string       `json:"storageClass,omitempty"`
	Checksum             *Checksum    `json:"checksum,omitempty"`
	PartsCount           int          `json:"partsCount"`
	Parts                []ObjectPart `json:"parts"`
	IsTruncated          bool         `json:"isTruncated"`
	NextPartNumberMarker int          `json:"nextPartNumberMarker,omitempty"`
}

// ObjectAttributesOptions select the version and the page of parts.
type ObjectAttributesOptions struct {
	VersionID string
	// MaxParts is 1 to 1000 (0: 1000); PartNumberMarker lists the parts
	// after that number.
	MaxParts         int
	PartNumberMarker int
}

// nonNilStrings returns values, or an empty slice for nil.
func nonNilStrings(values []string) []string {
	if values == nil {
		return []string{}
	}
	return values
}

