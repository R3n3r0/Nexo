// TestServiceConvention enforces docs/12 §12.2 on every package under
// internal/service: a service.go that declares the exported interfaces and
// no functions, at least one `var _ <Interface> = (*impl)(nil)` assertion
// against an interface of service.go in the implementation files, an
// unexported implementation type (no exported struct implements a
// service.go interface) and a generated mock for every interface.
func TestServiceConvention(t *testing.T) {
	root := "."
	entries, err := os.ReadDir(root)
	require.NoError(t, err)
	var checked int
	for _, e := range entries {
		if !e.IsDir() || e.Name() == "mock" {
			continue
		}
		checked++
		t.Run(e.Name(), func(t *testing.T) {
			checkPackage(t, filepath.Join(root, e.Name()))
		})
	}
	assert.Greater(t, checked, 0, "no service packages found")
}

func checkPackage(t *testing.T, dir string) {
	t.Helper()
	fset := token.NewFileSet()
	servicePath := filepath.Join(dir, "service.go")
	serviceFile, err := parser.ParseFile(fset, servicePath, nil, parser.ParseComments)
	require.NoError(t, err, "every service package has a service.go")

	// service.go: exported interfaces, no functions or methods.
	interfaces := map[string]bool{}
	for _, decl := range serviceFile.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Recv == nil || !isFuncAdapter(serviceFile, d) {
				t.Errorf("service.go declares %s: only interfaces, input/output types and documentation belong there", d.Name.Name)
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				if _, isIface := ts.Type.(*ast.InterfaceType); isIface && ts.Name.IsExported() {
					interfaces[ts.Name.Name] = true
				}
			}
		}
	}
	require.NotEmpty(t, interfaces, "service.go must declare at least one exported interface")

	// Implementation files: compile-time assertions and unexported types.
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	require.NoError(t, err)
	asserted := map[string]bool{}
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") || filepath.Base(path) == "service.go" {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, 0)
		require.NoError(t, err)
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gd.Specs {
				switch s := spec.(type) {
				case *ast.ValueSpec:
					if name, impl, ok := assertion(s); ok && interfaces[name] {
						asserted[name] = true
						assert.False(t, ast.IsExported(impl), "%s: implementation %s of %s must be unexported", filepath.Base(path), impl, name)
					}
				case *ast.TypeSpec:
					if _, isStruct := s.Type.(*ast.StructType); isStruct && s.Name.IsExported() {
						assert.False(t, implementsName(s.Name.Name, interfaces), "%s: exported struct %s looks like a service implementation", filepath.Base(path), s.Name.Name)
					}
				}
			}
		}
	}
	assert.NotEmpty(t, asserted, "no `var _ <Interface> = (*impl)(nil)` assertion for an interface of service.go")

	// Mocks: one file per interface, generated by mockery (.mockery.yaml).
	mockDir := filepath.Join(dir, "mock")
	names := make([]string, 0, len(interfaces))
	for n := range interfaces {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		mockFile := filepath.Join(mockDir, snakeCase(n)+".go")
		_, err := os.Stat(mockFile)
		assert.NoError(t, err, "interface %s has no generated mock (%s): add it to .mockery.yaml and run go generate ./...", n, mockFile)
	}
}

// TestMockCoverage extends rule 8 beyond the services: every exported
// interface of the transport, config and cli packages has its generated
// mock in <package>/mock (.mockery.yaml).
func TestMockCoverage(t *testing.T) {
	dirs := []string{
		"../config",
		"../cli",
		"../transport/http/httpx",
		"../transport/http/middleware",
		"../transport/http/server",
		"../transport/http/console",
		"../transport/http/s3",
		"../transport/http/admin",
		"../transport/rpc",
	}
	for _, dir := range dirs {
		t.Run(filepath.Base(dir), func(t *testing.T) {
			names := exportedInterfaces(t, dir)
			require.NotEmpty(t, names, "%s declares no interface: drop it from the list", dir)
			for _, n := range names {
				_, err := os.Stat(filepath.Join(dir, "mock", snakeCase(n)+".go"))
				assert.NoError(t, err, "interface %s of %s has no generated mock: add it to .mockery.yaml and run go generate ./...", n, dir)
			}
		})
	}
}

// TestNoMutableGlobals enforces "no global variables" (docs/12): outside
// the tests and the generated mocks, a package-level var may only be a
// compile-time assertion (`var _ I = ...`) or an error sentinel built with
// errors.New / fmt.Errorf. internal/version is the exception: its
// variables are set at link time (-ldflags -X).
func TestNoMutableGlobals(t *testing.T) {
	for _, root := range []string{"..", "../../cmd"} {
		err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				if d.Name() == "mock" || d.Name() == "testdata" || filepath.ToSlash(path) == "../version" {
					return filepath.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return nil
			}
			f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
			if err != nil {
				return err
			}
			for _, decl := range f.Decls {
				gd, ok := decl.(*ast.GenDecl)
				if !ok || gd.Tok != token.VAR {
					continue
				}
				for _, spec := range gd.Specs {
					vs := spec.(*ast.ValueSpec)
					for i, name := range vs.Names {
						if name.Name == "_" || (i < len(vs.Values) && isErrorSentinel(vs.Values[i])) {
							continue
						}
						t.Errorf("%s: package-level variable %s: use a function, a constant or a field of the implementation", path, name.Name)
					}
				}
			}
			return nil
		})
		require.NoError(t, err)
	}
}

// isErrorSentinel recognizes errors.New(...) and fmt.Errorf(...).
func isErrorSentinel(e ast.Expr) bool {
	call, ok := e.(*ast.CallExpr)
	if !ok {
		return false
	}
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	pkg, ok := sel.X.(*ast.Ident)
	if !ok {
		return false
	}
	return (pkg.Name == "errors" && sel.Sel.Name == "New") || (pkg.Name == "fmt" && sel.Sel.Name == "Errorf")
}

// exportedInterfaces lists the exported interface types (not aliases)
// declared by the non-test files of dir.
func exportedInterfaces(t *testing.T, dir string) []string {
	t.Helper()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	require.NoError(t, err)
	fset := token.NewFileSet()
	var names []string
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, 0)
		require.NoError(t, err)
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok || ts.Assign != 0 || !ts.Name.IsExported() {
					continue
				}
				if _, isIface := ts.Type.(*ast.InterfaceType); isIface {
					names = append(names, ts.Name.Name)
				}
			}
		}
	}
	sort.Strings(names)
	return names
}

// assertion recognizes `var _ Iface = (*impl)(nil)` and returns the
// interface and implementation names.
func assertion(s *ast.ValueSpec) (iface, impl string, ok bool) {
	if len(s.Names) != 1 || s.Names[0].Name != "_" || len(s.Values) != 1 {
		return "", "", false
	}
	ident, ok := s.Type.(*ast.Ident)
	if !ok {
		return "", "", false
	}
	call, ok := s.Values[0].(*ast.CallExpr)
	if !ok || len(call.Args) != 1 {
		return "", "", false
	}
	paren, ok := call.Fun.(*ast.ParenExpr)
	if !ok {
		return "", "", false
	}
	star, ok := paren.X.(*ast.StarExpr)
	if !ok {
		return "", "", false
	}
	implIdent, ok := star.X.(*ast.Ident)
	if !ok {
		return "", "", false
	}
	return ident.Name, implIdent.Name, true
}

// isFuncAdapter allows the one method shape service.go may carry: the
// Handle/Func adapter of a function type (like http.HandlerFunc), whose
// receiver is a func type declared in the same file.
func isFuncAdapter(f *ast.File, d *ast.FuncDecl) bool {
	recv := d.Recv.List[0].Type
	if star, ok := recv.(*ast.StarExpr); ok {
		recv = star.X
	}
	ident, ok := recv.(*ast.Ident)
	if !ok {
		return false
	}
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gd.Specs {
			if ts, ok := spec.(*ast.TypeSpec); ok && ts.Name.Name == ident.Name {
				_, isFunc := ts.Type.(*ast.FuncType)
				return isFunc
			}
		}
	}
	return false
}

// implementsName reports whether an exported struct is named like an
// implementation of one of the interfaces (Service → service, FooService...).
func implementsName(structName string, interfaces map[string]bool) bool {
	for n := range interfaces {
		if strings.EqualFold(structName, n) {
			return true
		}
	}
	return false
}

// snakeCase mirrors mockery's filename template ({{.InterfaceName | snakecase}}).
func snakeCase(s string) string {
	var b strings.Builder
	runes := []rune(s)
	for i, r := range runes {
		if i > 0 && r >= 'A' && r <= 'Z' {
			prev := runes[i-1]
			nextLower := i+1 < len(runes) && runes[i+1] >= 'a' && runes[i+1] <= 'z'
			if (prev >= 'a' && prev <= 'z') || (prev >= '0' && prev <= '9') || ((prev >= 'A' && prev <= 'Z') && nextLower) {
				b.WriteByte('_')
			}
		}
		b.WriteRune(r)
	}
	return strings.ToLower(b.String())
}
