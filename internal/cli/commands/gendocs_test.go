// readPages returns the generated pages of dir by file name.
func readPages(t *testing.T, dir string) map[string]string {
	t.Helper()
	files, err := filepath.Glob(filepath.Join(dir, commands.GenDocsPrefix+"*.md"))
	require.NoError(t, err)
	pages := make(map[string]string, len(files))
	for _, f := range files {
		b, err := os.ReadFile(f)
		require.NoError(t, err)
		pages[filepath.Base(f)] = string(b)
	}
	return pages
}

// availablePaths lists the file names cobra/doc writes for the tree of root:
// every available command (no hidden one, no help).
func availablePaths(root *cobra.Command) []string {
	var out []string
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		out = append(out, strings.ReplaceAll(c.CommandPath(), " ", "_")+".md")
		for _, sub := range c.Commands() {
			if sub.IsAvailableCommand() && !sub.IsAdditionalHelpTopicCommand() {
				walk(sub)
			}
		}
	}
	walk(root)
	sort.Strings(out)
	return out
}

// The reference of the real tree: one page per available command, no
// hidden command (gendocs itself), no date, no trailing blanks, and the
// same bytes on a second run (make docs-check, CI job "docs").
func TestGenDocsCommand(t *testing.T) {
	h := newHarness(t)
	dir := filepath.Join(t.TempDir(), "cli", "ref")

	r := h.mustRun("gendocs", dir)
	pages := readPages(t, dir)
	assert.Contains(t, r.stdout, "Wrote ")
	assert.Contains(t, r.stdout, " command pages to `"+dir+"`.")

	root := commands.NewRootCmd(h.deps)
	root.InitDefaultCompletionCmd()
	want := availablePaths(root)
	got := make([]string, 0, len(pages))
	for name := range pages {
		got = append(got, name)
	}
	sort.Strings(got)
	assert.Equal(t, want, got)
	assert.Greater(t, len(got), 40)
	assert.NotContains(t, pages, "nexoctl_gendocs.md", "hidden commands are not documented")
	assert.NotContains(t, pages, "nexoctl_help.md")
	assert.Contains(t, pages, "nexoctl_completion_bash.md")
	assert.Contains(t, pages["nexoctl_alias_list.md"], "## Aliases\n\n```\nnexoctl alias ls\n```")

	for name, page := range pages {
		assert.NotContains(t, page, "Auto generated by spf13/cobra", name)
		assert.True(t, strings.HasPrefix(page, "# nexoctl"), "%s has a level-1 title", name)
		assert.NotContains(t, page, "\n# ", "%s has a single level-1 heading", name)
		for i, line := range strings.Split(page, "\n") {
			assert.Equal(t, strings.TrimRight(line, " \t"), line, "%s:%d has trailing blanks", name, i+1)
		}
	}

	// A second run over the same tree writes the same pages.
	r = h.mustRun("gendocs", dir, "--json")
	recs := jsonLines(t, r.stdout)
	require.Len(t, recs, 1)
	assert.Equal(t, dir, recs[0]["dir"])
	assert.EqualValues(t, len(want), recs[0]["files"])
	assert.Equal(t, pages, readPages(t, dir))
}

func TestGenDocsUsage(t *testing.T) {
	h := newHarness(t)
	for _, args := range [][]string{{"gendocs"}, {"gendocs", "a", "b"}} {
		r := h.run(args...)
		assert.Equal(t, 2, r.code, "%v: %s", args, r.stderr)
	}
	r := h.mustRun("--help")
	assert.NotContains(t, r.stdout, "gendocs", "gendocs is hidden")
}

// GenMarkdownDocs over a small tree: stale pages are removed, other files
// are kept, the prose is escaped and the code is not.
func TestGenMarkdownDocs(t *testing.T) {
	newTree := func() *cobra.Command {
		root := &cobra.Command{Use: "nexoctl", Short: "Root of the_tree"}
		sub := &cobra.Command{
			Use:     "sub ALIAS/BUCKET",
			Aliases: []string{"s", "su"},
			Short:   "Match *.example.com keys",
			Long: "Rules match NEXO_SECRET_NAME and *.jpg, but not `a_b*` in code.\n\n" +
				"\tnexoctl sub local/*_x\n\n" +
				"Done.",
			Example: "  nexoctl sub local/b_*",
			Run:     func(*cobra.Command, []string) {},
		}
		sub.Flags().String("glob", "*", "pattern with * and _")
		hidden := &cobra.Command{Use: "secret", Hidden: true, Run: func(*cobra.Command, []string) {}}
		root.AddCommand(sub, hidden)
		return root
	}
	tests := []struct {
		name     string
		existing map[string]string
		check    func(t *testing.T, dir string, pages map[string]string)
	}{
		{
			name: "fresh directory",
			check: func(t *testing.T, _ string, pages map[string]string) {
				assert.Len(t, pages, 2)
				sub := pages["nexoctl_sub.md"]
				assert.Contains(t, sub, `Match \*.example.com keys`)
				assert.Contains(t, sub, `Rules match NEXO\_SECRET\_NAME and \*.jpg, but not `+"`a_b*`"+` in code.`)
				assert.Contains(t, sub, "\tnexoctl sub local/*_x\n", "indented code is kept")
				assert.Contains(t, sub, "  nexoctl sub local/b_*\n", "examples are kept")
				assert.Contains(t, sub, `pattern with * and _`, "flag tables are kept")
				aliases := strings.Index(sub, "## Aliases\n\n```\nnexoctl s\nnexoctl su\n```\n\n")
				require.GreaterOrEqual(t, aliases, 0, "aliases listed: %s", sub)
				assert.Less(t, aliases, strings.Index(sub, "## Examples"), "aliases before the examples")
				assert.NotContains(t, pages["nexoctl.md"], "## Aliases")
				assert.True(t, strings.HasPrefix(sub, "# nexoctl sub\n"), "title promoted: %s", sub)
				assert.Contains(t, sub, "\n## Synopsis\n")
				assert.Contains(t, pages["nexoctl.md"], "* [nexoctl sub](nexoctl_sub.md)\t - Match \\*.example.com keys")
				assert.Contains(t, pages["nexoctl.md"], `Root of the\_tree`)
				assert.NotContains(t, pages, "nexoctl_secret.md")
			},
		},
		{
			name: "stale pages removed, other files kept",
			existing: map[string]string{
				"nexoctl_removed.md": "old",
				"nexoctl_sub.md":     "old",
				"README.md":          "index",
			},
			check: func(t *testing.T, dir string, pages map[string]string) {
				assert.Len(t, pages, 2)
				assert.NotContains(t, pages, "nexoctl_removed.md")
				assert.NotEqual(t, "old", pages["nexoctl_sub.md"])
				b, err := os.ReadFile(filepath.Join(dir, "README.md"))
				require.NoError(t, err)
				assert.Equal(t, "index", string(b))
			},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := filepath.Join(t.TempDir(), "docs")
			require.NoError(t, os.MkdirAll(dir, 0o755))
			for name, content := range tt.existing {
				require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600))
			}
			n, err := commands.GenMarkdownDocs(newTree(), dir)
			require.NoError(t, err)
			pages := readPages(t, dir)
			assert.Equal(t, len(pages), n)
			tt.check(t, dir, pages)
		})
	}
}

func TestGenMarkdownDocsError(t *testing.T) {
	file := filepath.Join(t.TempDir(), "file")
	require.NoError(t, os.WriteFile(file, nil, 0o600))
	_, err := commands.GenMarkdownDocs(&cobra.Command{Use: "nexoctl"}, filepath.Join(file, "docs"))
	require.Error(t, err)
	assert.Contains(t, err.Error(), "gendocs")
}
